#!/usr/bin/env python3
"""Render a TTF into a 1-bpp 8x16 bitmap font (ASCII 32..126) as a C header.

usage: mkfont.py FONT.ttf SIZE OUT.h [preview.png]
Each glyph = 16 bytes, one per row, MSB = leftmost pixel.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

W, H = 8, 16
ttf, size, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
font = ImageFont.truetype(ttf, size)
ascent, descent = font.getmetrics()
y_off = (H - (ascent + descent)) // 2

glyphs = []
for ch in range(32, 127):
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)
    adv = font.getlength(chr(ch))
    d.text(((W - adv) / 2, y_off), chr(ch), font=font, fill=255)
    rows = []
    for y in range(H):
        b = 0
        for x in range(W):
            if img.getpixel((x, y)) >= 110:
                b |= 0x80 >> x
        rows.append(b)
    glyphs.append(rows)

with open(out, "w") as f:
    f.write(f"// Generated by tools/mkfont.py from {ttf.rsplit('/', 1)[-1]} @ {size}px. Do not edit.\n")
    f.write("#pragma once\n#include <stdint.h>\n#define FONT_W 8\n#define FONT_H 16\n#define FONT_FIRST 32\n#define FONT_LAST 126\n")
    f.write("static const uint8_t font8x16[95][16] = {\n")
    for ch, rows in zip(range(32, 127), glyphs):
        c = chr(ch).replace("\\", "backslash")
        f.write("  {" + ",".join(f"0x{b:02X}" for b in rows) + f"}}, // '{c}'\n")
    f.write("};\n")

if len(sys.argv) > 4:
    sheet = Image.new("L", (W * 32, H * 3), 0)
    for i, rows in enumerate(glyphs):
        for y, b in enumerate(rows):
            for x in range(W):
                if b & (0x80 >> x):
                    sheet.putpixel(((i % 32) * W + x, (i // 32) * H + y), 255)
    sheet.resize((sheet.width * 3, sheet.height * 3), Image.NEAREST).save(sys.argv[4])
